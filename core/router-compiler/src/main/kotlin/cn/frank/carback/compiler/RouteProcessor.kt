package cn.frank.carback.compiler

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.validate

/**
 * 扫描 @cn.frank.carback.route.Route 注解的 Fragment，
 * 在 impl 模块内生成 "<Feature>ImplRouterModule"（Hilt 多绑定装配代码，零反射）。
 *
 * KSP 选项：
 * - router.moduleName：生成的装配模块类名（由 FeatureImplConventionPlugin 按模块路径注入）
 */
class RouteProcessor(
    private val options: Map<String, String>,
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {

    private var processed = false

    override fun process(resolver: Resolver): List<KSAnnotated> {
        if (processed) {
            return emptyList()
        }
        val symbols = resolver.getSymbolsWithAnnotation(ANNOTATION_NAME)
            .filterIsInstance<KSClassDeclaration>()
            .toList()
        if (symbols.isEmpty()) {
            return emptyList()
        }
        if (symbols.any { !it.validate() }) {
            return emptyList()
        }
        processed = true

        val entries = mutableListOf<Pair<String, KSClassDeclaration>>()
        symbols.forEach { declaration ->
            if (declaration.qualifiedName == null) {
                logger.error("无法获取类全名（如匿名/局部类）：${declaration.simpleName.getShortName()}", declaration)
                return emptyList()
            }
            val path = declaration.annotations
                .first { it.shortName.getShortName() == "Route" }
                .arguments.firstOrNull { it.name?.getShortName() == "path" }
                ?.value as? String
            if (path.isNullOrBlank()) {
                logger.error("@Route path 不能为空：${declaration.qualifiedName?.asString()}", declaration)
                return emptyList()
            }
            if (!isFragmentSubclass(declaration)) {
                logger.error(
                    "@Route 只能标注在 androidx.fragment.app.Fragment 的子类上：${declaration.qualifiedName?.asString()}",
                    declaration,
                )
                return emptyList()
            }
            entries.add(path to declaration)
        }

        generateRouterModule(entries)
        return emptyList()
    }

    private fun isFragmentSubclass(declaration: KSClassDeclaration): Boolean {
        val queue = ArrayDeque(declaration.superTypes.toList())
        while (queue.isNotEmpty()) {
            val resolved = try {
                queue.removeFirst().resolve()
            } catch (e: Exception) {
                continue
            }
            val qualified = (resolved.declaration as? KSClassDeclaration)?.qualifiedName?.asString()
            if (qualified == "androidx.fragment.app.Fragment") {
                return true
            }
            val superDecl = resolved.declaration as? KSClassDeclaration ?: continue
            queue.addAll(superDecl.superTypes.toList())
        }
        return false
    }

    private fun generateRouterModule(entries: List<Pair<String, KSClassDeclaration>>) {
        val firstPackage = entries.first().second.packageName.asString()
        val moduleName = options[OPTION_MODULE_NAME]
            ?: (entries.first().second.simpleName.getShortName() + "ImplRouterModule")
        val methods = entries.joinToString(separator = "\n\n") { (path, declaration) ->
            val qualifiedName = declaration.qualifiedName?.asString().orEmpty()
            val methodName = "provide" + path.split('/')
                .filter { it.isNotBlank() }
                .joinToString("") { segment ->
                    segment.filter { it.isLetterOrDigit() }
                        .replaceFirstChar { it.uppercaseChar() }
                }
            """    @Provides
    @IntoSet
    public fun $methodName(): RouteEntry =
        RouteEntry("$path", $qualifiedName::class.java)"""
        }
        val source = buildString {
            appendLine("package $firstPackage")
            appendLine()
            appendLine("import cn.frank.carback.route.RouteEntry")
            appendLine("import dagger.Module")
            appendLine("import dagger.Provides")
            appendLine("import dagger.hilt.InstallIn")
            appendLine("import dagger.hilt.components.SingletonComponent")
            appendLine("import dagger.multibindings.IntoSet")
            appendLine()
            appendLine("/**")
            appendLine(" * Generated by :core:router-compiler (KSP). Do not modify.")
            appendLine(" * 装配本模块所有 @Route 声明的页面（Hilt 多绑定，零反射）。")
            appendLine(" */")
            appendLine("@Module")
            appendLine("@InstallIn(SingletonComponent::class)")
            appendLine("public object $moduleName {")
            appendLine()
            appendLine(methods)
            appendLine("}")
        }
        val dependencies = Dependencies(
            aggregating = true,
            *entries.mapNotNull { it.second.containingFile }.toTypedArray(),
        )
        codeGenerator.createNewFile(dependencies, firstPackage, moduleName).use { output ->
            output.write(source.toByteArray())
        }
        logger.info("RouteProcessor: generated $firstPackage.$moduleName with ${entries.size} routes")
    }

    companion object {
        const val ANNOTATION_NAME = "cn.frank.carback.route.Route"
        const val OPTION_MODULE_NAME = "router.moduleName"
    }
}

class RouteProcessorProvider : SymbolProcessorProvider {

    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        RouteProcessor(
            options = environment.options,
            codeGenerator = environment.codeGenerator,
            logger = environment.logger,
        )
}
